"""Build the Gazebo world (floor, tape, Navicode markers) from tape_map (no ROS)."""

import math

from agv_sim.tape_map import MARKER_SIZE, TAPE_WIDTH

TAPE_THICKNESS = 0.0013    # Naviq MTRK tape is 1.3 mm thick


def merge_straight(points, tol=1e-6):
    """Drop points that lie on a straight line, so straights become one box."""
    out = [points[0]]
    for p, q in zip(points[1:-1], points[2:]):
        a = out[-1]
        cross = (p[0]-a[0])*(q[1]-a[1]) - (p[1]-a[1])*(q[0]-a[0])
        if abs(cross) > tol:
            out.append(p)
    out.append(points[-1])
    return out


def box_visual(name, x, y, yaw, length, width, rgb):
    r, g, b = rgb
    return f'''
        <visual name="{name}">
          <pose>{x:.4f} {y:.4f} {TAPE_THICKNESS/2:.5f} 0 0 {yaw:.5f}</pose>
          <geometry><box><size>{length:.4f} {width:.4f} {TAPE_THICKNESS}</size></box></geometry>
          <material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse></material>
        </visual>'''


def tape_visuals(lines):
    """One thin box per polyline segment, slightly overlapped so curves look continuous."""
    out, k = [], 0
    for line in lines:
        pts = merge_straight(line)
        for (x0, y0), (x1, y1) in zip(pts[:-1], pts[1:]):
            length = math.hypot(x1-x0, y1-y0)
            if length < 1e-6:
                continue
            out.append(box_visual(f'tape_{k}', (x0+x1)/2, (y0+y1)/2, math.atan2(y1-y0, x1-x0),
                                  length + 0.002, TAPE_WIDTH, (1.0, 0.8, 0.0)))
            k += 1
    return out


def marker_visuals(stations):
    return [box_visual(f'navicode_{name}', st['marker'][0], st['marker'][1], 0.0,
                       MARKER_SIZE, MARKER_SIZE, (0.9, 0.1, 0.1))
            for name, st in stations.items()]


def world_sdf(lines, stations, name='agv_world'):
    visuals = ''.join(tape_visuals(lines) + marker_visuals(stations))
    return f'''<?xml version="1.0"?>
<!-- Generated by agv_sim.world_builder from tape_map.py. Do not edit by hand. -->
<sdf version="1.9">
  <world name="{name}">
    <physics name="physics" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <light name="sun" type="directional">
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
      <cast_shadows>true</cast_shadows>
    </light>
    <model name="floor">
      <static>true</static>
      <pose>3 2.5 0 0 0 0</pose>
      <link name="floor">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry></collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
          <material><ambient>0.6 0.6 0.6 1</ambient><diffuse>0.6 0.6 0.6 1</diffuse></material>
        </visual>
      </link>
    </model>
    <!-- Tape and markers are visual only: the virtual MTS160 reads tape_map.py,
         and no collision means the wheels never bump over 1.3 mm edges. -->
    <model name="track">
      <static>true</static>
      <link name="track">{visuals}
      </link>
    </model>
  </world>
</sdf>
'''


def write_world(path, name='agv_world'):
    from agv_sim.tape_map import station_loop
    lines, stations = station_loop()
    with open(path, 'w') as f:
        f.write(world_sdf(lines, stations, name))
    return path
